        // Owned synthetic Excel exports retained from userform-explicit-localgit-v6, before/QualificationForm.frx.
        // Raw logical streams preserve native uninitialized padding and every actual control/font property.
        [DataTestMethod]
        [DataRow("CheckBox")]
        [DataRow("ComboBox")]
        [DataRow("ListBox")]
        [DataRow("OptionButton")]
        [DataRow("TextBox")]
        [DataRow("ToggleButton")]
        public void CapturedNativeMorphLayoutsNormalizeWithoutDiscardingAProperty(string layout)
        {
            byte[][] raw = NativeMorphStreams(layout);
            byte[] first = (byte[])raw[0].Clone(), second = (byte[])raw[1].Clone();
            byte[][] normalized = FormStreamPadding.Normalize(raw[0], raw[1]);
            Assert.AreNotSame(raw[0], normalized[0], layout); Assert.AreNotSame(raw[1], normalized[1]);
            CollectionAssert.AreEqual(first, raw[0]); CollectionAssert.AreEqual(second, raw[1]);
            byte[][] repeated = FormStreamPadding.Normalize(normalized[0], normalized[1]);
            CollectionAssert.AreEqual(normalized[0], repeated[0]); CollectionAssert.AreEqual(normalized[1], repeated[1]);
            for (int stream = 0; stream < 2; stream++)
            {
                var padding = new HashSet<int>(NativeMorphPadding(layout, stream));
                for (int i = 0; i < raw[stream].Length; i++)
                {
                    Assert.AreEqual(padding.Contains(i) ? (byte)0 : raw[stream][i], normalized[stream][i], layout + ": byte " + i);
                    if (padding.Contains(i)) continue;
                    byte[] changed = (byte[])raw[stream].Clone(); changed[i] ^= 1;
                    byte[][] comparison = FormStreamPadding.Normalize(stream == 0 ? changed : raw[0], stream == 1 ? changed : raw[1]);
                    Assert.AreNotEqual(normalized[stream][i], comparison[stream][i], layout + ": stream " + stream + ", byte " + i);
                }
            }
        }

